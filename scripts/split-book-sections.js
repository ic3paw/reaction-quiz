// Run with: osascript -l JavaScript scripts/split-book-sections.js /path/to/book.pdf
// Keep the original figures; display separate regions without redrawing chemistry.
ObjC.import('Foundation');
ObjC.import('PDFKit');
ObjC.import('AppKit');

function read(path) {
  return ObjC.unwrap($.NSString.stringWithContentsOfFileEncodingError(path, $.NSUTF8StringEncoding, null));
}
function write(path, value) {
  if (!$(value).writeToFileAtomicallyEncodingError(path, true, $.NSUTF8StringEncoding, null)) throw Error('Cannot write '+path);
}
function run(args) {
  const pdf = $.PDFDocument.alloc.initWithURL($.NSURL.fileURLWithPath(args[0]));
  if (!pdf) throw Error('Cannot open source PDF');
  const book = JSON.parse(read('assets/book-data.js').split('const bookReactions = ')[1].trim().replace(/;$/, ''));
  const jobs = JSON.parse(read('scripts/book-figures.json'));
  const rendered = JSON.parse(read('scripts/book-figures.json.results.json'));
  const sections = {}, review = [];
  for (const id of Object.keys(book)) {
    const source = book[id], figure = source.reaction;
    if (id === 'fischer') {
      sections[id] = {outline:figure, importanceNote:'This reaction has no dedicated importance section in the supplied book. See Applications for the cited synthetic example.'};
      continue;
    }
    const page = pdf.pageAtIndex(figure.pdfPage - 1);
    const bounds = page.boundsForBox($.kPDFDisplayBoxMediaBox), height = bounds.size.height, width = bounds.size.width;
    const text = ObjC.unwrap(page.string), start = text.indexOf('Importance:');
    let end = text.indexOf('Mechanism:', start);
    if (end < 0) end = text.length;
    const rows = [];
    let cursor = start;
    for (const line of text.slice(start, end).split('\n')) {
      if (line.trim()) {
        const box = page.selectionForRange($.NSMakeRange(cursor, line.length)).boundsForPage(page);
        rows.push({text:line, x:box.origin.x / width, top:1-(box.origin.y+box.size.height)/height, bottom:1-box.origin.y/height, width:box.size.width/width});
      }
      cursor += line.length+1;
    }
    rows.sort((a,b)=>a.top-b.top);
    const prose = rows.filter(r=>r.x<0.15 && r.width>0.65 && r.text.split(/\s+/).length>8);
    if (!prose.length) throw Error('No importance paragraph: '+id);
    // The introductory prose is tightly set; the scheme starts after a larger gap.
    const leading = 10.4 / height;
    let last = prose[prose.length-1];
    for (const row of rows.filter(r=>r.top>last.top+0.001)) {
      if (row.top < last.bottom-0.004 || /^[\d,\-–]+$/.test(row.text.trim())) continue;
      if (row.top-last.top > leading*1.9 || row.x>0.17 || /:$/.test(row.text.trim())) break;
      if (!/[a-z]{2}/.test(row.text)) break;
      last = row;
    }
    let split = last.bottom + 0.005;
    const job = jobs.find(j=>j.file===figure.image);
    if (job.introEnd) {
      const index = text.indexOf(job.introEnd);
      if (index<0) throw Error('Missing known paragraph end: '+id);
      const box = page.selectionForRange($.NSMakeRange(index,job.introEnd.length)).boundsForPage(page);
      split=1-box.origin.y/height+0.005;
    }
    const existing = rendered.find(r=>r.file===figure.image);
    if (existing && !job.introEnd) {
      const crop=existing.crop, relative=(split-crop[1])/crop[3];
      if (relative<=0 || relative>=1) throw Error('Invalid section boundary: '+id);
      const dimensions={width:width*crop[2],height:height*crop[3]};
      sections[id]={
        outline:{...figure, caption:'General outline', viewport:{...dimensions,top:relative,bottom:1}},
        importance:{...figure, caption:'Importance', viewport:{...dimensions,top:0,bottom:relative}}
      };
    } else {
      const top=rows.find(r=>r.text==='Importance:').top-0.005;
      const rect=$.NSMakeRect(bounds.origin.x+width*0.11,bounds.origin.y+height*(1-split),width*0.78,height*(split-top));
      page.setBoundsForBox(rect,$.kPDFDisplayBoxCropBox);
      const image=page.thumbnailOfSizeForBox($.NSMakeSize(rect.size.width*2,rect.size.height*2),$.kPDFDisplayBoxCropBox);
      const bitmap=$.NSBitmapImageRep.imageRepWithData(image.TIFFRepresentation);
      const path='assets/book/'+id+'-importance.png';
      if (!bitmap.representationUsingTypeProperties($.NSBitmapImageFileTypePNG,$({})).writeToFileAtomically(path,true)) throw Error('Cannot write '+path);
      sections[id]={outline:{...figure,caption:'General outline'},importance:{image:path,printedPage:figure.printedPage,pdfPage:figure.pdfPage,caption:'Importance'}};
    }
    review.push({id,split,last:last.text,next:rows.filter(r=>r.top>split).slice(0,2).map(r=>r.text),relative:sections[id].outline.viewport?.top});
  }
  write('assets/book-sections.js','// Generated by scripts/split-book-sections.js from the supplied book.\nconst bookSections = '+JSON.stringify(sections,null,2)+';\n');
  write('.book-work/section-review.json',JSON.stringify(review,null,2));
  return JSON.stringify({sections:Object.keys(sections).length});
}

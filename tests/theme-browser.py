"""Check theme preferences, keyboard controls, and responsive navigation on localhost:8765."""
from playwright.sync_api import sync_playwright, expect

with sync_playwright() as p:
    browser = p.chromium.launch()
    context = browser.new_context(color_scheme='light', viewport={'width': 1440, 'height': 1000})
    page = context.new_page()
    errors = []
    page.on('pageerror', lambda error: errors.append(str(error)))
    page.goto('http://127.0.0.1:8765/')
    root = page.locator('html')
    toggle = page.get_by_role('button', name='Dark mode', exact=True)
    expect(root).to_have_attribute('data-theme', 'light')
    page.emulate_media(color_scheme='dark')
    expect(root).to_have_attribute('data-theme', 'dark')
    expect(toggle).to_have_attribute('aria-pressed', 'true')
    toggle.focus()
    page.keyboard.press('Space')
    expect(root).to_have_attribute('data-theme', 'light')
    page.reload()
    expect(root).to_have_attribute('data-theme', 'light')
    toggle.click()
    page.reload()
    expect(root).to_have_attribute('data-theme', 'dark')
    other = context.new_page()
    other.goto('http://127.0.0.1:8765/')
    expect(other.locator('html')).to_have_attribute('data-theme', 'dark')
    other.get_by_role('button', name='Dark mode', exact=True).click()
    expect(root).to_have_attribute('data-theme', 'light')
    other.close()
    toggle.click()
    page.locator('.menu-toggle').click()
    page.get_by_role('link', name='Reactions', exact=True).click()
    expect(page.locator('.menu-toggle')).to_have_attribute('aria-expanded', 'true')
    expect(page.locator('.nav-item.active')).to_have_text('Reactions')
    page.wait_for_timeout(900)
    page.screenshot(path='/tmp/namereactiondb-dark-desktop.png')
    for width in [1440, 1200, 1199, 768, 390, 320]:
        page.set_viewport_size({'width': width, 'height': 900})
        page.wait_for_timeout(900)
        assert page.evaluate('document.documentElement.scrollWidth <= innerWidth'), width
        brand = page.locator('.brand').bounding_box()
        controls = page.locator('.header-controls').bounding_box()
        assert brand['x'] + brand['width'] <= controls['x'], width
        for link in page.locator('.nav-item').all():
            box = link.bounding_box()
            assert box['x'] >= 0 and box['x'] + box['width'] <= width, (width, box)
            if width >= 1200:
                assert box['x'] >= brand['x'] + brand['width'], width
                assert box['x'] + box['width'] <= controls['x'], width
        if width == 390:
            page.screenshot(path='/tmp/namereactiondb-dark-mobile.png')
    page.set_viewport_size({'width': 1440, 'height': 1000})
    page.locator('.menu-toggle').click()
    page.locator('.reaction-name').first.click()
    dialog = page.locator('#reaction-dialog')
    expect(dialog).to_be_visible()
    expect(dialog.locator('.book-figure img').first).to_have_css('background-color', 'rgb(255, 255, 255)')
    expect(dialog).to_have_css('background-color', 'rgb(24, 24, 27)')
    page.screenshot(path='/tmp/namereactiondb-dark-reaction.png')
    page.keyboard.press('Escape')
    page.evaluate("location.hash = 'dashboard'")
    page.get_by_role('button', name='Quiz all selected', exact=True).click()
    quiz = page.locator('#quiz-dialog')
    expect(quiz).to_have_css('background-color', 'rgb(24, 24, 27)')
    expect(quiz.locator('.answer').first).to_have_css('color', 'rgb(237, 237, 240)')
    current = page.evaluate('quiz.questions[quiz.index].id')
    quiz.locator(f'[data-answer]:not([data-answer="{current}"])').first.click()
    expect(quiz.locator('.answer.correct')).to_have_css('background-color', 'rgb(33, 53, 38)')
    expect(quiz.locator('.answer.incorrect')).to_have_css('background-color', 'rgb(53, 35, 42)')
    blocked = browser.new_context(color_scheme='dark')
    blocked.add_init_script("Object.defineProperty(window, 'localStorage', {get() { throw new Error('Storage blocked'); }});")
    fallback = blocked.new_page()
    fallback.goto('http://127.0.0.1:8765/')
    expect(fallback.locator('html')).to_have_attribute('data-theme', 'dark')
    fallback.get_by_role('button', name='Dark mode', exact=True).click()
    expect(fallback.locator('html')).to_have_attribute('data-theme', 'light')
    assert not errors, errors
    browser.close()
    print('Theme preferences, cross-tab sync, keyboard, mobile layout, and diagram checks passed.')
